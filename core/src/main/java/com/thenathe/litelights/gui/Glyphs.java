    private final String[] rows;

    Glyphs(String... rows) {
        this.rows = rows;
    }

    public int width() {
        return rows[0].length();
    }

    public int height() {
        return rows.length;
    }

    public void draw(GuiGraphicsExtractor graphics, int x, int y, int colour) {
        for (int row = 0; row < rows.length; row++) {
            String line = rows[row];
            int column = 0;
            while (column < line.length()) {
                if (line.charAt(column) != '#') {
                    column++;
                    continue;
                }
                int runEnd = column;
                while (runEnd < line.length() && line.charAt(runEnd) == '#') {
                    runEnd++;
                }
                graphics.fill(x + column, y + row, x + runEnd, y + row + 1, colour);
                column = runEnd;
            }
        }
    }

    public void drawCentred(GuiGraphicsExtractor graphics, int x, int y, int w, int h, int colour) {
        draw(graphics, x + (w - width()) / 2, y + (h - height()) / 2, colour);
    }
